//! The design's screens as Unreal Slate, bound to the game's screens: the engine draws and lays
//! out every screen, and the game says which is shown, what it reads and which commands it admits
//! (the schema, `crate::schema`). Three files, generated together so they cannot drift:
//!
//! - `BendScreens.h` (public): per screen, the engine's types for what it reads (`FBend<S>Read`)
//!   and the commands it admits (`EBend<S>Command`), its widget (`SBend<S>Screen`, which can only
//!   give its own commands), and `SBendScreens`, the switcher over them all;
//! - `BendScreens.cpp`: the widgets, laid out as designed: auto layout as horizontal and vertical
//!   boxes with the design's padding and gaps, a free frame's children on a constraint canvas
//!   anchored as their constraints pin them, surfaces as rounded box brushes, a pressable's
//!   `Idle`, `Hovered` and `Pressed` variants as one button style and its `Selected` variant as
//!   another, texts in the design's fonts from the files the engine stages;
//! - `BendScreensWire.h` (private): the parse of a shown screen from the C ABI (`ub_shown`, through
//!   the generated header's typed `ub_<screen>_read_of`) into those types, and the print of a
//!   command to the ABI's `ub_acted`.
//!
//! Hover and press are Slate's own. What the generator cannot draw faithfully it refuses by
//! name, as the converter does.

